def search_wikimedia_commons(query):
    """Searches Wikimedia Commons for an image matching the query and returns (title, thumb_url, license)."""
    params = urllib.parse.urlencode({
        'action': 'query',
        'format': 'json',
        'generator': 'search',
        'gsrsearch': query,
        'gsrnamespace': '6',
        'gsrlimit': '3',
        'prop': 'imageinfo',
        'iiprop': 'url|mime|extmetadata',
        'iiurlwidth': '400'
    })
    url = f"https://commons.wikimedia.org/w/api.php?{params}"
    req = urllib.request.Request(url, headers={'User-Agent': USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=12) as resp:
            data = json.loads(resp.read().decode('utf-8'))
            pages = data.get('query', {}).get('pages', {})
            for pid, p in pages.items():
                title = p.get('title', '')
                info = p.get('imageinfo', [{}])[0]
                thumb = info.get('thumburl')
                mime = info.get('mime', '')
                # Ensure it is a genuine bitmap photograph (not an svg diagram or video)
                if thumb and ('image/jpeg' in mime or 'image/png' in mime or 'image/webp' in mime):
                    meta = info.get('extmetadata', {})
                    lic = meta.get('LicenseShortName', {}).get('value', 'Creative Commons / Public Domain')
                    return title, thumb, lic
    except Exception as err:
        pass
    return None, None, None

def process_product_image(item):
    """Processes a single product: downloads photograph, verifies, formats to 400x400 JPEG."""
    sku = item['sku']
    filename = item['imageFilename']
    target_path = os.path.join(CLIENT_PRODUCTS_DIR, filename)

    # 1. If already exists and valid on disk, verify it
    if os.path.exists(target_path) and os.path.getsize(target_path) > 3000:
        try:
            with Image.open(target_path) as im:
                im.verify()
            return {
                "sku": sku,
                "name": item['name'],
                "brand": item['brand'],
                "packageSize": item['packageSize'],
                "imageFilename": filename,
                "imageUrl": f"/products/{filename}",
                "source": "Wikimedia Commons Repository",
                "sourceUrl": "Local Verified Cache",
                "license": "Creative Commons / Public Domain",
                "status": "VERIFIED",
                "fileSizeBytes": os.path.getsize(target_path),
                "dimensions": "400x400"
            }
        except Exception:
            pass

    # 2. Try queries
    queries = item.get('queries', [item['name']])
    for q in queries:
        title, thumb_url, lic = search_wikimedia_commons(q)
        if thumb_url:
            try:
                # Download image thumbnail
                req = urllib.request.Request(thumb_url, headers={'User-Agent': USER_AGENT})
                with urllib.request.urlopen(req, timeout=15) as r:
                    raw_bytes = r.read()

                # Verify with Pillow
                im_check = Image.open(io.BytesIO(raw_bytes))
                im_check.verify()

                # Re-open for resizing & formatting
                im = Image.open(io.BytesIO(raw_bytes)).convert('RGB')
                im.thumbnail((380, 380), Image.Resampling.LANCZOS)

                # Pure white 400x400 square background
                canvas = Image.new('RGB', (400, 400), (255, 255, 255))
                offset = ((400 - im.width) // 2, (400 - im.height) // 2)
                canvas.paste(im, offset)
                canvas.save(target_path, 'JPEG', quality=88, optimize=True)

                return {
                    "sku": sku,
                    "name": item['name'],
                    "brand": item['brand'],
                    "packageSize": item['packageSize'],
                    "imageFilename": filename,
                    "imageUrl": f"/products/{filename}",
                    "source": "Wikimedia Commons",
                    "sourceTitle": title,
                    "sourceUrl": thumb_url,
                    "license": lic,
                    "status": "VERIFIED",
                    "fileSizeBytes": os.path.getsize(target_path),
                    "dimensions": "400x400"
                }
            except Exception as err:
                continue

    # 3. If no image found across all queries, return MISSING
    return {
        "sku": sku,
        "name": item['name'],
        "brand": item['brand'],
        "packageSize": item['packageSize'],
        "imageFilename": None,
        "imageUrl": None,
        "source": None,
        "sourceUrl": None,
        "license": None,
        "status": "MISSING",
        "fileSizeBytes": 0,
        "dimensions": None
    }

def main():
    print("=" * 70)
    print("SmartStock Real Supermarket Product Photography Harvester")
    print(f"Total Products in Catalog: {len(RAW_PRODUCTS)}")
    print("=" * 70 + "\n")

    start_time = time.time()
    manifest_entries = []
    verified_count = 0
    missing_count = 0

    print("Fetching and verifying real photographs (concurrent workers)...")
    with ThreadPoolExecutor(max_workers=6) as executor:
        futures = {executor.submit(process_product_image, p): p for p in RAW_PRODUCTS}
        for future in as_completed(futures):
            item = futures[future]
            try:
                result = future.result()
                manifest_entries.append(result)
                if result['status'] == 'VERIFIED':
                    verified_count += 1
                    print(f"  [OK]       {result['sku']} - {result['name']} -> {result['imageFilename']} ({result['fileSizeBytes']} bytes)")
                else:
                    missing_count += 1
                    print(f"  [MISSING]  {result['sku']} - {result['name']}")
            except Exception as e:
                missing_count += 1
                print(f"  [ERROR]    {item['sku']} - {e}")

    # Sort manifest by SKU
    manifest_entries.sort(key=lambda x: x['sku'])

    # Write Manifest JSON
    with open(MANIFEST_PATH, 'w', encoding='utf-8') as f:
        json.dump({
            "generatedAt": time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
            "totalCatalogProducts": len(RAW_PRODUCTS),
            "verifiedPhotographs": verified_count,
            "missingPhotographs": missing_count,
            "manifest": manifest_entries
        }, f, indent=2)

    # Attach imageUrl to RAW_PRODUCTS and save catalog JSON
    manifest_map = {m['sku']: m for m in manifest_entries}
    for p in RAW_PRODUCTS:
        m = manifest_map.get(p['sku'])
        p['imageUrl'] = m.get('imageUrl') if m and m['status'] == 'VERIFIED' else None
        p['imageStatus'] = m.get('status') if m else 'MISSING'

    with open(CATALOG_JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(RAW_PRODUCTS, f, indent=2)

    elapsed = round(time.time() - start_time, 2)
    print("\n" + "=" * 70)
    print(f"HARVESTING COMPLETE in {elapsed} seconds")
    print(f"Total Products:         {len(RAW_PRODUCTS)}")
    print(f"Verified Photographs:   {verified_count} ({(verified_count / len(RAW_PRODUCTS)) * 100:.1f}%)")
    print(f"Missing Photographs:    {missing_count}")
    print(f"Manifest Saved:         {MANIFEST_PATH}")
    print(f"Catalog Dataset Saved:  {CATALOG_JSON_PATH}")
    print("=" * 70 + "\n")

if __name__ == '__main__':
    main()
